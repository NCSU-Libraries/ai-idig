#!/usr/bin/env python3
"""Writes the copies of the page's prompts, so the page stays the one source.

    python3 tools/extract_prompts.py

It reads every prompt box (a ``::: {.prompt}`` div holding a code block) in site/index.qmd and writes:

- site/_starter-anatomy.md: the starter prompt in "Describe the activity", cut into its five PARTS. The reasons
  under the figure are written in index.qmd: keep the two in step.
- instructor/prompts.txt: every prompt in page order, under the heading it sits in, for the instructor's second
  screen. Skipped when instructor/ isn't there, as in a fresh clone of the public repo.

Run it after changing any prompt on the page.
"""

import html
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGE = ROOT / "site" / "index.qmd"
ANATOMY = ROOT / "site" / "_starter-anatomy.md"
PROMPTS = ROOT / "instructor" / "prompts.txt"

PARTS = [("P", "Persona"), ("A", "Aim"), ("R", "Recipients"), ("T", "Theme"), ("S", "Structure")]


def prompts(text):
    """Yield (heading, prompt) for each prompt box, in page order."""
    heading = ""
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        m = re.match(r"^(#{1,3}) (.+?)(\s*\{.*\})?\s*$", line)
        if m:
            heading = m.group(2)
        if re.match(r"^::: \{\.prompt( \.[a-z-]+)*\}$", line.strip()):
            indent = len(line) - len(line.lstrip())
            j = i + 1
            if not lines[j].strip().startswith("```"):
                sys.exit(f"index.qmd line {j + 1}: a prompt box must start with a code fence")
            body = []
            j += 1
            while not lines[j].strip().startswith("```"):
                body.append(lines[j][indent:] if lines[j].strip() else "")
                j += 1
            yield heading, "\n".join(body).strip("\n")
            i = j
        i += 1


def anatomy(prompt):
    paras = [p for p in re.split(r"\n\s*\n", prompt) if p.strip()]
    if len(paras) != len(PARTS):
        sys.exit(f"The starter prompt has {len(paras)} paragraphs; the figure expects {len(PARTS)} (PARTS).")
    out = [
        "<!-- Generated by tools/extract_prompts.py from the starter prompt in index.qmd. Don't edit. -->",
        "",
        "```{=html}",
        '<figure class="anatomy" role="group" aria-label="The starter prompt, cut into its five PARTS">',
    ]
    for (letter, name), para in zip(PARTS, paras):
        tag = "pre" if "\n" in para else "p"
        out.append(
            f'<div class="part"><span class="num" aria-hidden="true">{letter}</span>'
            f'<span class="visually-hidden">{name}: </span><{tag}>{html.escape(para, quote=False)}</{tag}></div>'
        )
    out += ["</figure>", "```", ""]
    return "\n".join(out)


def main():
    found = list(prompts(PAGE.read_text(encoding="utf-8")))
    starter = [p for h, p in found if h == "Describe the activity"]
    if len(starter) != 1:
        sys.exit("Expected exactly one prompt under 'Describe the activity'.")
    ANATOMY.write_text(anatomy(starter[0]), encoding="utf-8")
    print(f"Wrote {ANATOMY.relative_to(ROOT)}")
    if PROMPTS.parent.is_dir():
        parts = ["Every prompt on the page, in order. Generated by tools/extract_prompts.py; don't edit.\n"]
        for n, (h, p) in enumerate(found, 1):
            parts.append(f"=== {n}. {h} ===\n{p}\n")
        PROMPTS.write_text("\n".join(parts), encoding="utf-8")
        print(f"Wrote {PROMPTS.relative_to(ROOT)} ({len(found)} prompts)")


if __name__ == "__main__":
    main()
